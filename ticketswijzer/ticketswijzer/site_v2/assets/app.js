/* TicketsWijzer — client-side filter/sort/search for listing pages.
   Operates on already-rendered .card elements (data is server-generated by build.py),
   so it works on a static host with no backend. */
(function () {
  var grid = document.getElementById("grid");
  if (!grid) return;

  var cards = Array.prototype.slice.call(grid.querySelectorAll(".card"));
  var search = document.getElementById("q");
  var sortSel = document.getElementById("sort");
  var chips = document.querySelectorAll(".chip");
  var activeCat = "alle";

  function apply() {
    var q = (search && search.value ? search.value : "").trim().toLowerCase();
    var visible = cards.filter(function (c) {
      var catOk = activeCat === "alle" || c.dataset.cat === activeCat;
      var hay = (c.dataset.naam + " " + c.dataset.plaats).toLowerCase();
      var qOk = !q || hay.indexOf(q) !== -1;
      return catOk && qOk;
    });

    var mode = sortSel ? sortSel.value : "save";
    visible.sort(function (a, b) {
      if (mode === "price") return parseFloat(a.dataset.cheapest) - parseFloat(b.dataset.cheapest);
      if (mode === "rating") return parseFloat(b.dataset.rating) - parseFloat(a.dataset.rating);
      if (mode === "name") return a.dataset.naam.localeCompare(b.dataset.naam);
      return parseFloat(b.dataset.savings) - parseFloat(a.dataset.savings); // default: savings
    });

    cards.forEach(function (c) { c.style.display = "none"; });
    visible.forEach(function (c) { c.style.display = ""; grid.appendChild(c); });

    var empty = document.getElementById("empty");
    if (empty) empty.style.display = visible.length ? "none" : "";
  }

  if (search) search.addEventListener("input", apply);
  if (sortSel) sortSel.addEventListener("change", apply);
  chips.forEach(function (chip) {
    chip.addEventListener("click", function () {
      activeCat = chip.dataset.cat;
      chips.forEach(function (c) { c.classList.remove("active"); });
      chip.classList.add("active");
      apply();
    });
  });

  apply();
})();
